/**
 * Cloudflare adapter glue for DimaScore (not app code).
 * 1. Vercel parity: browsers see what Vercel sends (s-maxage / CDN-only directives stripped,
 *    default `public, max-age=0, must-revalidate`).
 * 2. next.config.ts headers() (CSP/HSTS/… on '/(.*)', CORS on '/api/(.*)') on EVERY Worker
 *    response, including middleware redirects/429s (Vercel applies them; OpenNext may not).
 *    Values come from the build's routes-manifest, so the CSP has the same realtime host.
 * 3. Per-data-centre response cache (Workers Cache API, $0) for 200 GETs with s-maxage>0 and no
 *    Set-Cookie, kept for that s-maxage (e.g. /api/v1/live's short shared cache).
 * 4. scheduled(): the 9 Vercel crons (vercel.json) called in-process with Bearer CRON_SECRET.
 *    Only runs if wrangler.jsonc registers Cron Triggers (none on the preview).
 */
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- file only exists after the build
// @ts-ignore - generated by `opennextjs-cloudflare build`
import handler from '../.open-next/worker.js';
// Durable Object behind the OpenNext ISR revalidation queue (open-next.config.ts `queue: doQueue`).
// Must be exported from the Worker entry so the NEXT_CACHE_DO_QUEUE binding (wrangler.jsonc) can find it.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- file only exists after the build
// @ts-ignore - generated by `opennextjs-cloudflare build`
export { DOQueueHandler } from '../.open-next/worker.js';
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- file only exists after the build
// @ts-ignore - generated by `next build`
import routesManifest from '../.open-next/server-functions/default/.next/routes-manifest.json';
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- file only exists after the build
// @ts-ignore - generated by `next build`
import fontManifest from '../.open-next/server-functions/default/.next/server/next-font-manifest.json';

type Env = { CRON_SECRET?: string; [k: string]: unknown };
type Ctx = { waitUntil(p: Promise<unknown>): void; passThroughOnException?(): void };
type HeaderRule = { source: string; regex: string; headers: { key: string; value: string }[] };

const RULES: { re: RegExp; headers: [string, string][] }[] = (
  (routesManifest as { headers: HeaderRule[] }).headers ?? []
).map((r) => ({ re: new RegExp(r.regex), headers: r.headers.map((h) => [h.key, h.value]) }));

// next/font preloads. On Vercel, Next sends these as a `Link: rel=preload` header (and so leaves
// them out of the HTML). On Workers the middleware's hreflang `Link` header replaces that header,
// so the preload was lost entirely; add it back on HTML responses that lack it.
const FONT_PRELOADS: string[] = [
  ...new Set(Object.values((fontManifest as { app?: Record<string, string[]> }).app ?? {}).flat()),
].map(
  (f) => `</_next/${f}>; rel=preload; as="font"; crossorigin=""; type="font/${f.split('.').pop()}"`,
);

const NO_STORE = 'private, no-cache, no-store, max-age=0, must-revalidate';
const VARY = [
  'rsc',
  'next-router-state-tree',
  'next-router-prefetch',
  'next-router-segment-prefetch',
  'next-url',
];
const ORIG_CC = 'x-cf-origin-cache-control';

function vercelParity(input: Response, pathname: string): Response {
  const response = new Response(input.body, input);
  const h = response.headers;
  h.delete('vercel-cdn-cache-control');
  h.delete('cdn-cache-control');
  const cc = h.get('cache-control');
  if (cc && /s-maxage/i.test(cc)) {
    const kept = cc
      .split(',')
      .map((d) => d.trim())
      .filter((d) => d && !/^(s-maxage|stale-while-revalidate)(=|$)/i.test(d));
    const hasMaxAge = kept.some((d) => /^max-age=/i.test(d));
    h.set('cache-control', hasMaxAge ? kept.join(', ') : 'public, max-age=0, must-revalidate');
  }
  if (!h.has('cache-control')) h.set('cache-control', 'public, max-age=0, must-revalidate');
  else if (h.get('cache-control') === NO_STORE && !h.has('set-cookie'))
    h.set('cache-control', 'public, max-age=0, must-revalidate');
  // Vercel serves robots.txt (and other text/plain routes) with an explicit UTF-8 charset.
  if (h.get('content-type') === 'text/plain') h.set('content-type', 'text/plain; charset=utf-8');
  if (FONT_PRELOADS.length && (h.get('content-type') ?? '').startsWith('text/html')) {
    const link = h.get('link') ?? '';
    const missing = FONT_PRELOADS.filter((v) => !link.includes(v.slice(0, v.indexOf('>') + 1)));
    if (missing.length) h.set('link', [...missing, ...(link ? [link] : [])].join(', '));
  }
  for (const rule of RULES) {
    if (!rule.re.test(pathname)) continue;
    for (const [k, v] of rule.headers) if (!h.has(k)) h.set(k, v);
  }
  return response;
}

// ISR revalidation requests come from the OpenNext DO queue (DOQueueHandler) as
// `HEAD <page>` with `x-isr: 1` + `x-prerender-revalidate`, through WORKER_SELF_REFERENCE. The DO
// only counts a revalidation as done when the response has `x-nextjs-cache: REVALIDATED`, but Next
// in minimal mode never sets that header on postponed (PPR) HTML responses (app-page-runtime:
// `!didPostpone || isPrefetchRSCRequest`), although the page IS regenerated and written to R2.
// Without this, every successful revalidation logs "The revalidation for … cannot be done".
function markIsrRevalidation(request: Request, res: Response): Response {
  if (
    request.method !== 'HEAD' ||
    request.headers.get('x-isr') !== '1' ||
    !request.headers.get('x-prerender-revalidate') ||
    res.status !== 200 ||
    res.headers.has('x-nextjs-cache')
  )
    return res;
  const out = new Response(res.body, res);
  out.headers.set('x-nextjs-cache', 'REVALIDATED');
  return out;
}

// vercel.json crons (UTC). Several paths share */15.
const CRONS: Record<string, string[]> = {
  '0 3 * * *': ['/api/cron/reference-data'],
  '15 3 * * *': ['/api/cron/teams'],
  '0,30 * * * *': ['/api/cron/fixtures-schedule'],
  '15,45 * * * *': ['/api/cron/standings'],
  '0 5 * * *': ['/api/cron/top-scorers'],
  '*/15 * * * *': ['/api/cron/fixture-details', '/api/cron/live-details'],
  // Five minutes after fixture-details/live-details, whose back-to-back burst of API-Football calls
  // pushed finalize-stale into the per-minute 429 (seen 14:15, 14:30, 14:45 on 20 Nov).
  '5,20,35,50 * * * *': ['/api/cron/finalize-stale'],
  // Cloudflare cron syntax: day-of-week 0 is rejected (1-7 or names), so Sunday is SUN.
  '0 4 * * SUN': ['/api/cron/squads-refresh'],
};

const worker = {
  async fetch(request: Request, env: Env, ctx: Ctx): Promise<Response> {
    const url = new URL(request.url);
    const pathname = url.pathname;
    if (request.method !== 'GET') {
      const res: Response = await handler.fetch(request, env, ctx);
      return vercelParity(markIsrRevalidation(request, res), pathname);
    }

    const key = new URL(request.url);
    for (const name of VARY) {
      const value = request.headers.get(name);
      if (value !== null) key.searchParams.append(`__cfv_${name}`, value);
    }
    // Host is part of the key (apex/www/.com redirect differently).
    const keyRequest = new Request(key.toString(), { method: 'GET' });
    const cache = (caches as unknown as { default: Cache }).default;

    const hit = await cache.match(keyRequest);
    if (hit) {
      const response = new Response(hit.body, hit);
      const original = response.headers.get(ORIG_CC);
      if (original === null || original === '') response.headers.delete('cache-control');
      else response.headers.set('cache-control', original);
      response.headers.delete(ORIG_CC);
      response.headers.set('x-cf-html-cache', 'HIT');
      return vercelParity(response, pathname);
    }

    const response: Response = await handler.fetch(request, env, ctx);
    const cc = response.headers.get('cache-control') ?? '';
    const sMaxAge = /(?:^|,)\s*s-maxage=(\d+)/i.exec(cc);
    const ttl = sMaxAge ? Number(sMaxAge[1]) : 0;
    if (response.status === 200 && ttl > 0 && !response.headers.has('set-cookie')) {
      const stored = new Response(response.clone().body, response);
      stored.headers.set(ORIG_CC, cc);
      stored.headers.set('cache-control', `public, max-age=${ttl}`);
      ctx.waitUntil(cache.put(keyRequest, stored));
    }
    return vercelParity(response, pathname);
  },

  async scheduled(event: { cron: string }, env: Env, ctx: Ctx): Promise<void> {
    const paths = CRONS[event.cron];
    if (!paths) {
      console.error('[cron] unknown schedule', event.cron);
      return;
    }
    if (!env.CRON_SECRET) {
      console.error('[cron] CRON_SECRET not set; skipping', paths.join(','));
      return;
    }
    for (const path of paths) {
      const req = new Request('https://dimascore.ma' + path, {
        headers: { authorization: `Bearer ${env.CRON_SECRET}`, 'user-agent': 'vercel-cron/1.0' },
      });
      const res: Response = await handler.fetch(req, env, ctx);
      console.log('[cron]', path, '->', res.status, (await res.text()).slice(0, 300));
    }
  },
};

export default worker;
