#!/usr/bin/env python3
"""Regenerates src/lib/og/og-static-fallback.ts: the last-resort 1200x630 OG PNG (brand colours
and the DimaScore wordmark, no text that needs a locale). renderOgImage serves these bytes when
both the real image and the fallback image fail to render, so an OG route can never 500.
Needs: python3 with Pillow and fonttools. Run from the repo root after build-og-font.sh."""
import base64, io, re
from PIL import Image, ImageDraw, ImageFont

W, H = 1200, 630
src = open("src/lib/og/og-font-data.ts").read()
font_bytes = base64.b64decode(re.search(r'"([A-Za-z0-9+/=]+)"', src).group(1))
font = ImageFont.truetype(io.BytesIO(font_bytes), 96)

img = Image.new("RGB", (W, H), "#0d1117")
d = ImageDraw.Draw(img)
for x in range(W):  # accent bar, same gradient as the rendered images
    t = x / (W - 1)
    c = tuple(round(a + (b - a) * t) for a, b in zip((0x00, 0xA8, 0x7F), (0x3A, 0x56, 0xD4)))
    d.line([(x, 0), (x, 5)], fill=c)
w1 = d.textlength("Dima", font=font)
w2 = d.textlength("Score", font=font)
x0 = (W - (w1 + w2)) / 2
y0 = H / 2 + 34  # baseline; centres the cap height
d.text((x0, y0), "Dima", font=font, fill="#e6edf3", anchor="ls")
d.text((x0 + w1, y0), "Score", font=font, fill="#3a56d4", anchor="ls")

buf = io.BytesIO()
img.quantize(colors=32).save(buf, "PNG", optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode()
with open("src/lib/og/og-static-fallback.ts", "w") as f:
    f.write("// GENERATED by scripts/og-font/build-og-static-fallback.py. Do not edit.\n")
    f.write("// Last-resort 1200x630 OG image (PNG), served when rendering fails.\n")
    f.write(f'export const OG_STATIC_FALLBACK_PNG_BASE64 =\n  "{b64}";\n')
print(len(buf.getvalue()), "bytes")
