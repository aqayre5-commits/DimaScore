#!/bin/bash
# Regenerates src/lib/og/og-font-data.ts: IBM Plex Sans Arabic Bold (SIL OFL 1.1, the site's own
# Arabic UI font), subset to Latin + Latin-1/Extended-A + Arabic + general punctuation, with the
# Arabic shaping features (init/medi/fina/isol/rlig/liga/calt/ccmp/mark/mkmk/kern).
# Needs: curl, python3 with fonttools (pyftsubset).
set -euo pipefail
cd "$(dirname "$0")/../.."
tmp=$(mktemp -d)
curl -sSfL -o "$tmp/full.ttf" https://github.com/google/fonts/raw/main/ofl/ibmplexsansarabic/IBMPlexSansArabic-Bold.ttf
pyftsubset "$tmp/full.ttf" \
  --unicodes="U+0020-007E,U+00A0-017F,U+0600-06FF,U+2010-2027,U+2030-205E,U+200C-200F" \
  --layout-features='kern,mark,mkmk,init,medi,fina,isol,rlig,liga,calt,ccmp,locl' \
  --no-hinting --desubroutinize --output-file="$tmp/og.ttf" 2>/dev/null
{
  echo '// GENERATED by scripts/og-font/build-og-font.sh. Do not edit.'
  echo '// IBM Plex Sans Arabic Bold, subset. Copyright 2017 IBM Corp. SIL Open Font License 1.1'
  echo '// (https://openfontlicense.org). Used only by the opengraph-image routes.'
  printf 'export const OG_FONT_BASE64 =\n  %s;\n' "\"$(base64 -w0 "$tmp/og.ttf")\""
} > src/lib/og/og-font-data.ts
rm -rf "$tmp"
